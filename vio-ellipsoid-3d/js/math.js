// ============================================================
// Математика модели: информационная матрица Λ (3×3),
// собственное разложение методом Якоби, квадратичная форма.
// Матрицы — обычные массивы строк [[..],[..],[..]], без библиотек.
// ============================================================

// Порог «тьмы»: собственное число ниже EPS_DARK считаем нулём —
// соответствующее направление ненаблюдаемо.
export const EPS_DARK = 1e-9;

export function zero3() {
  return [[0, 0, 0], [0, 0, 0], [0, 0, 0]];
}

// Bearing-измерение: фича видна по лучу r (единичный вектор от камеры
// к фиче), измеряется только направление, без дальности. Информация
// возникает в плоскости, перпендикулярной лучу:
//   Λ += w · (I − r rᵀ)
// Глубина вдоль луча не наблюдается — (I − r rᵀ) проецирует её в ноль.
export function addBearing(L, r, w) {
  for (let i = 0; i < 3; i++)
    for (let j = 0; j < 3; j++)
      L[i][j] += w * ((i === j ? 1 : 0) - r[i] * r[j]);
}

// Фича на однородной (бестекстурной) стене с нормалью n: оптический
// поток различает движение только поперёк стены, вдоль стены сдвиг
// неотличим. Информация только вдоль нормали:
//   Λ += w · n nᵀ
export function addNormal(L, n, w) {
  for (let i = 0; i < 3; i++)
    for (let j = 0; j < 3; j++)
      L[i][j] += w * n[i] * n[j];
}

// Квадратичная форма dᵀΛd — сколько информации накоплено вдоль
// пробного направления d (единичного). Бежит от λ_max до λ_min.
export function quadForm(L, d) {
  let s = 0;
  for (let i = 0; i < 3; i++)
    for (let j = 0; j < 3; j++)
      s += d[i] * L[i][j] * d[j];
  return s;
}

// ------------------------------------------------------------
// Метод Якоби для симметричной 3×3 матрицы.
// Идея: симметричная матрица диагонализуется последовательностью
// вращений Гивенса J(p,q,φ). На каждом шаге берём наибольший по
// модулю внедиагональный элемент a_pq и выбираем угол φ так, чтобы
// после A ← Jᵀ A J он обнулился:
//   tan(2φ) = 2·a_pq / (a_qq − a_pp)
// Накопленное произведение вращений V даёт собственные векторы
// (столбцы V), диагональ A — собственные числа.
// Для 3×3 сходится за ~10 вращений до машинной точности.
// ------------------------------------------------------------
export function jacobiEig3(Ain) {
  // рабочая копия (не портим вход)
  const a = [Ain[0].slice(), Ain[1].slice(), Ain[2].slice()];
  const V = [[1, 0, 0], [0, 1, 0], [0, 0, 1]];

  for (let iter = 0; iter < 64; iter++) {
    // наибольший по модулю внедиагональный элемент (p,q)
    let p = 0, q = 1, mx = Math.abs(a[0][1]);
    if (Math.abs(a[0][2]) > mx) { p = 0; q = 2; mx = Math.abs(a[0][2]); }
    if (Math.abs(a[1][2]) > mx) { p = 1; q = 2; mx = Math.abs(a[1][2]); }
    if (mx < 1e-13) break; // матрица уже диагональная

    // угол вращения: tan(2φ) = 2·a_pq / (a_qq − a_pp)
    const phi = 0.5 * Math.atan2(2 * a[p][q], a[q][q] - a[p][p]);
    const c = Math.cos(phi), s = Math.sin(phi);

    // A ← Jᵀ A J: сначала столбцы (A·J), затем строки (Jᵀ·A)
    for (let k = 0; k < 3; k++) {
      const akp = a[k][p], akq = a[k][q];
      a[k][p] = c * akp - s * akq;
      a[k][q] = s * akp + c * akq;
    }
    for (let k = 0; k < 3; k++) {
      const apk = a[p][k], aqk = a[q][k];
      a[p][k] = c * apk - s * aqk;
      a[q][k] = s * apk + c * aqk;
    }
    // V ← V·J — накапливаем собственные векторы в столбцах V
    for (let k = 0; k < 3; k++) {
      const vkp = V[k][p], vkq = V[k][q];
      V[k][p] = c * vkp - s * vkq;
      V[k][q] = s * vkp + c * vkq;
    }
  }

  // диагональ — собственные числа; сортируем по убыванию: λ1 ≥ λ2 ≥ λ3
  const out = [0, 1, 2].map(i => ({
    l: a[i][i],
    v: [V[0][i], V[1][i], V[2][i]],
  }));
  out.sort((x, y) => y.l - x.l);
  return out;
}
